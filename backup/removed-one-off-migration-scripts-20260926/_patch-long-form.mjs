const raw = await readFile(TARGET, 'utf8')
const line = raw.split('\n')
// 定位记录：以 `  "id": {` 开头到下一个同级记录前的 `  },`
const findRecordRange = (id) => {
  const start = line.findIndex((l) => l === `  "${id}": {`)
  if (start < 0) throw new Error('record not found: ' + id)
  let depth = 0
  for (let i = start; i < line.length; i++) {
    for (const ch of line[i]) {
      if (ch === '{') depth++
      else if (ch === '}') depth--
    }
    if (depth === 0) return [start, i]
  }
  throw new Error('unterminated record: ' + id)
}

const jsonEscape = (s) => JSON.stringify(s)

let patchedCount = 0
for (const [id, patch] of Object.entries(P)) {
  const [start, end] = findRecordRange(id)
  const body = line.slice(start, end + 1)
  for (const [stepId, newBody] of Object.entries(patch.steps)) {
    const idLine = body.findIndex((l) => l.trim() === `"id": "${stepId}",`)
    if (idLine < 0) throw new Error(`step not found: ${id}.${stepId}`)
    const bodyLine = body.findIndex((l, i) => i > idLine && l.trimStart().startsWith('"body": '))
    if (bodyLine < 0) throw new Error(`body line not found: ${id}.${stepId}`)
    const indent = body[bodyLine].match(/^\s*/)[0]
    const extra = (X[id] ?? {})[stepId] ?? ''
    const finalBody = newBody + (extra ? extra : '')
    body[bodyLine] = `${indent}"body": ${jsonEscape(finalBody)},`
  }
  const explLine = body.findIndex((l) => l.trimStart().startsWith('"explanation": '))
  body[explLine] = `${body[explLine].match(/^\s*/)[0]}"explanation": ${jsonEscape(patch.explanation)},`
  // examples 与 remarks 整块替换
  // examples 在部分记录里是单行空数组 `"examples": [],`，也要能匹配。
  const idxOf = (key) => body.findIndex((l) => l.trim() === `"${key}": [` || l.trim() === `"${key}": [],`)
  const exStart = idxOf('examples')
  const rmStart = idxOf('remarks')
  const refStart = idxOf('references')
  if (exStart < 0 || rmStart < 0 || refStart < 0) throw new Error('block not found: ' + id)
  const ind = (l) => (l.match(/^\s*/) || [''])[0]
  const base = ind(body[exStart])
  const inner = base + '  '
  const exBlock = [`${base}"examples": [`]
  patch.examples.forEach((item, index) => {
    exBlock.push(`${inner}{`)
    exBlock.push(`${inner}  "title": ${jsonEscape(item.title)},`)
    exBlock.push(`${inner}  "body": ${jsonEscape(item.body)}`)
    exBlock.push(index === patch.examples.length - 1 ? `${inner}}` : `${inner}},`)
  })
  exBlock.push(`${base}],`)
  const rmBlock = [`${base}"remarks": [`]
  for (const item of patch.remarks) rmBlock.push(`${inner}${jsonEscape(item)},`)
  rmBlock.push(`${base}],`)
  const rebuilt = [
    ...body.slice(0, exStart),
    ...exBlock,
    ...rmBlock,
    ...body.slice(refStart),
  ]
  line.splice(start, end - start + 1, ...rebuilt)
  patchedCount++
}


/**
 * Documentation Generator
 * Auto-generates API documentation from definitions
 */

export class DocumentationGenerator {
  /**
   * Generate complete API documentation
   */
  async generate(apiDefinition) {
    const doc = {
      autoGenerated: true,
      generatedAt: new Date(),
      readme: this.generateReadme(apiDefinition),
      endpoints: this.generateEndpointDocs(apiDefinition.endpoints),
      examples: this.generateExamples(apiDefinition),
      authentication: this.generateAuthDocs(),
      rateLimits: this.generateRateLimitDocs(apiDefinition.rateLimits),
      errors: this.generateErrorDocs(),
      changelog: []
    };

    return doc;
  }

  /**
   * Generate README
   */
  generateReadme(api) {
    return `# ${api.name}

${api.description}

**Version:** ${api.version}
**Publisher:** ${api.publisher.displayName}
**Category:** ${api.category.join(', ')}

## Quick Start

\`\`\`javascript
const consumer = new APIConsumer({ apiKey: 'your-api-key' });

const result = await consumer.call('${api.apiId}', {
  endpoint: '${api.endpoints[0]?.path}',
  method: '${api.endpoints[0]?.method}',
  data: { /* your data */ }
});
\`\`\`

## Pricing

${this.formatPricing(api.pricing)}

## Rate Limits

${this.formatRateLimits(api.rateLimits)}

## Support

For questions or issues, contact ${api.publisher.displayName}.
`;
  }

  /**
   * Generate endpoint documentation
   */
  generateEndpointDocs(endpoints) {
    return endpoints.map(endpoint => ({
      path: endpoint.path,
      method: endpoint.method,
      description: endpoint.description || 'No description provided',
      parameters: this.extractParameters(endpoint),
      responses: this.generateResponseExamples(endpoint),
      example: this.generateEndpointExample(endpoint)
    }));
  }

  /**
   * Generate code examples
   */
  generateExamples(api) {
    const examples = [];

    // JavaScript example
    examples.push({
      language: 'javascript',
      title: 'Node.js Example',
      code: this.generateJavaScriptExample(api)
    });

    // cURL example
    examples.push({
      language: 'bash',
      title: 'cURL Example',
      code: this.generateCurlExample(api)
    });

    // Python example
    examples.push({
      language: 'python',
      title: 'Python Example',
      code: this.generatePythonExample(api)
    });

    return examples;
  }

  generateJavaScriptExample(api) {
    const endpoint = api.endpoints[0];
    return `// Install: npm install @formula-nebula/api-client

const { APIConsumer } = require('@formula-nebula/api-client');

const consumer = new APIConsumer({
  apiKey: process.env.FN_API_KEY
});

async function example() {
  try {
    const result = await consumer.call('${api.apiId}', {
      endpoint: '${endpoint.path}',
      method: '${endpoint.method}',
      data: ${JSON.stringify(endpoint.exampleRequest || {}, null, 2)}
    });

    console.log('Success:', result.data);
  } catch (error) {
    console.error('Error:', error.message);
  }
}

example();`;
  }

  generateCurlExample(api) {
    const endpoint = api.endpoints[0];
    const dataArg = endpoint.method === 'POST' || endpoint.method === 'PUT'
      ? ` \\\n  -d '${JSON.stringify(endpoint.exampleRequest || {})}'`
      : '';

    return `curl -X ${endpoint.method} \\
  https://api.formula-nebula.com/v1/${api.apiId}${endpoint.path} \\
  -H "Authorization: Bearer YOUR_API_KEY" \\
  -H "Content-Type: application/json"${dataArg}`;
  }

  generatePythonExample(api) {
    const endpoint = api.endpoints[0];
    return `# Install: pip install formula-nebula

import os
from formula_nebula import APIConsumer

consumer = APIConsumer(api_key=os.getenv('FN_API_KEY'))

try:
    result = consumer.call(
        api_id='${api.apiId}',
        endpoint='${endpoint.path}',
        method='${endpoint.method}',
        data=${JSON.stringify(endpoint.exampleRequest || {}, null, 2).replace(/"/g, "'")}
    )
    print('Success:', result['data'])
except Exception as e:
    print('Error:', str(e))`;
  }

  /**
   * Generate authentication documentation
   */
  generateAuthDocs() {
    return {
      type: 'API Key',
      description: 'All requests must include a valid API key',
      methods: [
        {
          method: 'Authorization Header',
          example: 'Authorization: Bearer YOUR_API_KEY',
          recommended: true
        },
        {
          method: 'X-API-Key Header',
          example: 'X-API-Key: YOUR_API_KEY'
        },
        {
          method: 'Query Parameter',
          example: '?apiKey=YOUR_API_KEY',
          note: 'Not recommended for production'
        }
      ],
      security: 'Keep your API key secret. Never commit it to version control or expose it in client-side code.'
    };
  }

  /**
   * Generate rate limit documentation
   */
  generateRateLimitDocs(rateLimits) {
    return {
      limits: rateLimits,
      headers: {
        'X-RateLimit-Limit-Minute': 'Requests allowed per minute',
        'X-RateLimit-Remaining-Minute': 'Requests remaining this minute',
        'X-RateLimit-Reset-Minute': 'Timestamp when limit resets',
        'Retry-After': 'Seconds to wait before retrying (429 responses)'
      },
      handling: `When rate limited, the API returns a 429 status code with a Retry-After header indicating when to retry.`
    };
  }

  /**
   * Generate error documentation
   */
  generateErrorDocs() {
    return {
      format: {
        success: false,
        error: {
          code: 'number',
          message: 'string',
          details: 'object (optional)'
        }
      },
      codes: [
        { code: 400, title: 'Bad Request', description: 'Invalid request parameters' },
        { code: 401, title: 'Unauthorized', description: 'Missing or invalid API key' },
        { code: 403, title: 'Forbidden', description: 'Insufficient permissions' },
        { code: 404, title: 'Not Found', description: 'API or endpoint not found' },
        { code: 429, title: 'Too Many Requests', description: 'Rate limit exceeded' },
        { code: 500, title: 'Internal Server Error', description: 'Server error occurred' }
      ]
    };
  }

  // Helper methods

  extractParameters(endpoint) {
    // Extract from path params: /users/:id -> id
    const pathParams = (endpoint.path.match(/:(\w+)/g) || [])
      .map(p => p.substring(1));

    return {
      path: pathParams.map(name => ({
        name,
        type: 'string',
        required: true,
        description: `${name} identifier`
      })),
      query: endpoint.queryParams || [],
      body: endpoint.bodySchema || {}
    };
  }

  generateResponseExamples(endpoint) {
    return {
      200: {
        description: 'Success',
        example: endpoint.exampleResponse || { success: true, data: {} }
      },
      400: {
        description: 'Bad Request',
        example: { success: false, error: { code: 400, message: 'Invalid parameters' } }
      },
      429: {
        description: 'Rate Limit Exceeded',
        example: { success: false, error: { code: 429, message: 'Rate limit exceeded' } }
      }
    };
  }

  generateEndpointExample(endpoint) {
    return {
      request: {
        method: endpoint.method,
        path: endpoint.path,
        headers: {
          'Authorization': 'Bearer YOUR_API_KEY',
          'Content-Type': 'application/json'
        },
        body: endpoint.exampleRequest
      },
      response: {
        status: 200,
        body: endpoint.exampleResponse || { success: true, data: {} }
      }
    };
  }

  formatPricing(pricing) {
    if (pricing.model === 'free') {
      return 'This API is free to use.';
    }

    if (pricing.model === 'tiered') {
      const tiers = pricing.tiers.map(t =>
        `- **${t.name}**: ${t.price === 0 ? 'Free' : `$${t.price}/month`} - ${t.limit} requests`
      ).join('\n');
      return `Tiered pricing:\n${tiers}`;
    }

    if (pricing.model === 'usage') {
      return `Pay-as-you-go: $${pricing.pricePerCall} per request`;
    }

    return 'Contact publisher for pricing details.';
  }

  formatRateLimits(rateLimits) {
    return `- ${rateLimits.requestsPerMinute} requests per minute
- ${rateLimits.requestsPerDay} requests per day
- Burst limit: ${rateLimits.burstLimit || rateLimits.requestsPerMinute * 2}`;
  }
}

export default DocumentationGenerator;

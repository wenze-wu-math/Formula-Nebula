/* ───────────────────────── 相机 ─────────────────────────
 * 机位不再写死坐标，而是**按盘面实际大小解析求出**（见 scene.js）：
 *     dist = R·sin(φ) / tan(vFov/2) × fitMargin
 * 这样改 LAYOUT.radiusOuter 时取景会自动跟着变，不会出现
 * "画面偏空、公式小得看不清"或"盘超出画面"。
 *
 * ── 俯仰角为什么取 40° ──
 * 盘面是扁的（厚径比约 0.12），这会带来一个纯投影问题：
 * 侧视时整片盘被压成一条窄带，不同半径的公式在屏幕上叠成一团。
 * 实测屏幕平均层数（scripts/sweep-camera-tilt.mjs）：
 *     8° → 1.85 层   14° → 1.52 层   26° → 1.31 层
 *    40° → 1.21 层   52° → 1.14 层   75° → 1.05 层
 * 而且**旋臂只有从上方才看得出形状** —— 侧视时多条旋臂重合成一条线。
 * 40° 是"看得清旋臂 + 重叠明显缓解 + 仍有立体感"的平衡点。
 *
 * ⚠ 改 startTilt 必须同步改 LAYOUT.radialSquash = 1/sin(startTilt)。
 */

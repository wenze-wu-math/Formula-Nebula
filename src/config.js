  // ── 次序 vs 可读性的取舍系数 ──
  // 松弛不看重要度，本来会把"越中心越重要"的次序打乱（秩相关 −0.99 → −0.88）。
  // 所以每个节点的半径带被夹在相邻重要度节点的中线之间。

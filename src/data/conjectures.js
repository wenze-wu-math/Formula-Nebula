/**
 * ═══════════════════════════════════════════════════════════════
 *  猜想星团 · 未定论的知识
 * ═══════════════════════════════════════════════════════════════
 *
 *  ── 为什么要给猜想单独一个星团 ──
 *
 *  主星系放的是**已经定论**的知识：定理、构造、不变量。
 *  但代数几何最有生命力的部分，恰恰是那些还没有定论的东西 ——
 *  猜想、开问题、刚被推翻的猜测。它们是这门学科的**活动边缘**。
 *
 *  它们不该混在主星系里，理由不是审美而是**语义冲突**：
 *
 *    · 主星系的核心语义是「越中心越基础」。一个 1990 年才提出、
 *      至今未解的猜想，既不"基础"，也不该按"基础程度"排序。
 *    · 未定论的知识天然带一个**状态维度**（未解决 / 部分解决 /
 *      已证明 / 已推翻），主星系的节点没有这个维度，硬塞进去
 *      就只能把这个信息丢掉。
 *
 *  ── 于是给它一个独立的球状星团 ──
 *
 *  形态本身就是信息：主星系是薄盘（旋臂、核球、明确的方向性），
 *  星团是球对称的。看一眼就知道这是另一类对象，不需要读图例。
 *  真实宇宙里也正如此：盘星系 + 一群球状的伴生星团。
 *
 *  内部仍沿用主星系那套**正交分解**，所以核心语义不会丢：
 *    · 球心距 ← importance（越著名、越核心的猜想越靠球心）
 *    · 球面方向 ← field（6 个领域各占球面一个方向，形成 6 个"星座"）
 *  这样「越中心越重要」在星团里依然成立，验证脚本可以复用同一套
 *  秩相关断言（见 scripts/verify-cluster.mjs）。
 *
 *  ── 状态怎么表达 ──
 *
 *  每个公式左侧一个小色点，颜色 = status。这是**唯一**能一眼区分
 *  "这条已经被证明了"和"这条还悬着"的手段 —— 光看公式本身看不出来。
 *  色点用几何体而不是贴图：它要被随时换色（切领域着色时），
 *  而贴图染色要走材质，几何体直接改 material.color 就行。
 *
 *  ── 关于准确性的说明 ──
 *
 *  status 字段记的是**截至编写时**的公认状态。数学的状态会变
 *  （Kakeya 猜想在 R³ 被解决就是最近的事），所以这条信息是带时间戳的：
 *  year 记提出年份，detail 里尽量写明是谁、在哪一年解决的。
 *  若某条的 status 已经过时，改这一个字段即可，不需要动布局 ——
 *  status 只影响色点颜色，不参与位置计算。
 *
 *  字段说明见 knowledge.js 顶部（本文件多了 status / field / year / proposer）。
 */

